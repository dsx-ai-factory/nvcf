func TestBuildSkillZipProducesSortedManifestAndDataFiles(t *testing.T) {
	files := []skillFile{
		{Path: "nvcf-self-managed-installation/SKILL.md", Body: []byte("install skill\n")},
		{Path: "nvcf-self-managed-cli/SKILL.md", Body: []byte("cli skill\n")},
	}

	zipBytes, manifest, err := buildSkillZip(files)
	if err != nil {
		t.Fatalf("buildSkillZip: %v", err)
	}
	repeatZipBytes, _, err := buildSkillZip([]skillFile{files[1], files[0]})
	if err != nil {
		t.Fatalf("repeat buildSkillZip: %v", err)
	}
	if !bytes.Equal(zipBytes, repeatZipBytes) {
		t.Fatal("buildSkillZip output changed when input order changed")
	}

	if manifest.GeneratedAt != deterministicGeneratedAt {
		t.Fatalf("GeneratedAt = %q, want %q", manifest.GeneratedAt, deterministicGeneratedAt)
	}
	if manifest.TotalFiles != 2 {
		t.Fatalf("TotalFiles = %d, want 2", manifest.TotalFiles)
	}
	if len(manifest.Files) != 2 {
		t.Fatalf("Files length = %d, want 2", len(manifest.Files))
	}
	if manifest.Files[0].Path != "nvcf-self-managed-cli/SKILL.md" {
		t.Fatalf("Files[0].Path = %q, want sorted CLI skill first", manifest.Files[0].Path)
	}

	wantSum := sha256.Sum256([]byte("cli skill\n"))
	if manifest.Files[0].SHA256 != hex.EncodeToString(wantSum[:]) {
		t.Fatalf("Files[0].SHA256 = %q, want %q", manifest.Files[0].SHA256, hex.EncodeToString(wantSum[:]))
	}
	if manifest.Files[0].Size != len("cli skill\n") {
		t.Fatalf("Files[0].Size = %d, want %d", manifest.Files[0].Size, len("cli skill\n"))
	}

	reader, err := zip.NewReader(bytes.NewReader(zipBytes), int64(len(zipBytes)))
	if err != nil {
		t.Fatalf("zip.NewReader: %v", err)
	}
	manifestBody, err := fs.ReadFile(reader, "data/manifest.json")
	if err != nil {
		t.Fatalf("read manifest from zip: %v", err)
	}
	var fromZip manifestJSON
	if err := json.Unmarshal(manifestBody, &fromZip); err != nil {
		t.Fatalf("unmarshal zipped manifest: %v", err)
	}
	if fromZip.TotalBytes != len("cli skill\n")+len("install skill\n") {
		t.Fatalf("TotalBytes = %d, want source byte total", fromZip.TotalBytes)
	}
	for name, want := range map[string]string{
		"data/nvcf-self-managed-cli/SKILL.md":          "cli skill\n",
		"data/nvcf-self-managed-installation/SKILL.md": "install skill\n",
	} {
		body, err := fs.ReadFile(reader, name)
		if err != nil {
			t.Fatalf("read %s from zip: %v", name, err)
		}
		if string(body) != want {
			t.Fatalf("%s body = %q, want %q", name, string(body), want)
		}
	}
}

func TestValidateSkillPathRejectsUnsafeAndUnexpectedPaths(t *testing.T) {
	cases := []string{
		"../SKILL.md",
		"/nvcf-self-managed-cli/SKILL.md",
		"nvcf-self-managed-cli/../SKILL.md",
		"nvcf-self-managed-cli/.secret",
		"nvcf-self-managed-installation/_draft.md",
		"other-skill/SKILL.md",
	}

	for _, path := range cases {
		t.Run(path, func(t *testing.T) {
			if err := validateSkillPath(path); err == nil {
				t.Fatalf("validateSkillPath(%q) = nil, want error", path)
			}
		})
	}
}

func TestRun(t *testing.T) {
	t.Run("missing output", func(t *testing.T) {
		err := run(nil)
		if err == nil || !strings.Contains(err.Error(), "-out is required") {
			t.Fatalf("run error = %v, want missing output error", err)
		}
	})

	t.Run("output without input", func(t *testing.T) {
		err := run([]string{"-out", filepath.Join(t.TempDir(), "generated.go")})
		if err == nil || !strings.Contains(err.Error(), "at least one source skill file is required") {
			t.Fatalf("run error = %v, want missing input error", err)
		}
	})

	t.Run("skills root with positional input", func(t *testing.T) {
		err := run([]string{"-out", filepath.Join(t.TempDir(), "generated.go"), "-skills-root", t.TempDir(), "input.md"})
		if err == nil || !strings.Contains(err.Error(), "-skills-root cannot be combined") {
			t.Fatalf("run error = %v, want conflicting input error", err)
		}
	})

	assertGenerated := func(t *testing.T, output string) {
		t.Helper()
		body, err := os.ReadFile(output)
		if err != nil {
			t.Fatalf("read generated file: %v", err)
		}
		if !strings.Contains(string(body), "// Code generated by skilldatagen; DO NOT EDIT.") {
			t.Fatal("generated file is missing code generation header")
		}
		formatted, err := format.Source(body)
		if err != nil {
			t.Fatalf("generated file is not valid Go: %v", err)
		}
		if !bytes.Equal(formatted, body) {
			t.Fatal("generated Go source is not gofmt formatted")
		}
	}

	t.Run("positional input", func(t *testing.T) {
		dir := filepath.Join(t.TempDir(), "ai-tooling", "user", "skills", "nvcf-self-managed-cli")
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
		input := filepath.Join(dir, "SKILL.md")
		if err := os.WriteFile(input, []byte("skill content\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		output := filepath.Join(t.TempDir(), "nested", "generated.go")
		if err := run([]string{"-out", output, input}); err != nil {
			t.Fatalf("run: %v", err)
		}
		assertGenerated(t, output)
	})

	t.Run("skills root walks allowed nested files and ignores build files", func(t *testing.T) {
		base := t.TempDir()
		root := filepath.Join(base, "ai-tooling", "user", "skills")
		files := map[string]string{
			"nvcf-self-managed-cli/SKILL.md":                          "cli skill\n",
			"nvcf-self-managed-cli/references/nested/guide.md":        "nested guide\n",
			"nvcf-self-managed-installation/SKILL.md":                "install skill\n",
			"nvcf-self-managed-installation/references/BUILD.bazel": "ignored build file\n",
		}
		for name, body := range files {
			filename := filepath.Join(root, filepath.FromSlash(name))
			if err := os.MkdirAll(filepath.Dir(filename), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(filename, []byte(body), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		output := filepath.Join(base, "generated.go")
		if err := run([]string{"-out", output, "-skills-root", root}); err != nil {
			t.Fatalf("run: %v", err)
		}
		assertGenerated(t, output)
		body, err := os.ReadFile(output)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(body), "Code generated by skilldatagen") {
			t.Fatal("generated output is missing expected header")
		}
	})

	t.Run("positional input read error", func(t *testing.T) {
		missing := filepath.Join(t.TempDir(), "ai-tooling", "user", "skills", "nvcf-self-managed-cli", "missing.md")
		err := run([]string{"-out", filepath.Join(t.TempDir(), "generated.go"), missing})
		if err == nil || !strings.Contains(err.Error(), "read "+missing) {
			t.Fatalf("run error = %v, want source read context", err)
		}
	})

	t.Run("skills root walk error", func(t *testing.T) {
		root := filepath.Join(t.TempDir(), "ai-tooling", "user", "skills")
		err := run([]string{"-out", filepath.Join(t.TempDir(), "generated.go"), "-strip-prefix", filepath.Dir(filepath.Dir(filepath.Dir(root))), "-skills-root", root})
		if err == nil || !strings.Contains(err.Error(), "walk ") {
			t.Fatalf("run error = %v, want walk context", err)
		}
	})
}
